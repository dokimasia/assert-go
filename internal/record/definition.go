//go:build ignore

// The generator of definition_gen.go, which go generate runs in the directory
// of the package record. It writes the version of the vendored definition,
// which the file VERSION of conformance contains, as the constant Definition.
package main

import (
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"
)

// source is the text of definition_gen.go, with a verb for the version.
const source = `// Code generated by "go run definition.go"; DO NOT EDIT.

package record

// Definition is the version of the definition that this module implements,
// which every call record states: the version of the vendored definition,
// which the file VERSION of conformance contains.
const Definition = %q
`

func main() {
	version, err := os.ReadFile(filepath.Join("..", "..", "conformance", "VERSION"))
	if err != nil {
		fmt.Fprintln(os.Stderr, "definition:", err)
		os.Exit(1)
	}
	formatted, err := format.Source(fmt.Appendf(nil, source, strings.TrimSpace(string(version))))
	if err != nil {
		fmt.Fprintln(os.Stderr, "definition:", err)
		os.Exit(1)
	}
	if err := os.WriteFile("definition_gen.go", formatted, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "definition:", err)
		os.Exit(1)
	}
}
